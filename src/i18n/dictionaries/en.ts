/**
 * English。
 *
 * 用 `satisfies DeepPartial<typeof zh>` 而不是 `: TranslationTree`：
 * 后者会把字面量拓宽成索引签名，键拼错要等运行到那一行才发现；
 * 前者按 zh 的真实结构校验「已有的键」，值仍保持各自的字面量。
 * 缺键是允许的 —— provider 会回退到中文兜底。
 */
type DeepPartial<T> = {
  [K in keyof T]?: T[K] extends string ? string : DeepPartial<T[K]>;
};

